#!/usr/bin/env node
/**
 * Generates server/engine/tz-country.ts: IANA time zone name -> ISO 3166
 * country, used to infer a visitor's country from the browser time zone when
 * no CDN country header is present.
 *
 * Source: the IANA tz database (public domain) — zone.tab gives one row per
 * (country, zone), including per-country names such as Europe/Oslo; the
 * `backward` file adds old and alternate names (Asia/Calcutta, Europe/Kiev,
 * US/Pacific, ...). Re-run once or twice a year; an unknown name simply
 * yields no country.
 *
 * Usage:
 *   node scripts/generate-tz-country.mjs            # downloads from github.com/eggert/tz
 *   node scripts/generate-tz-country.mjs <dir>      # reads <dir>/zone.tab and <dir>/backward
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const RAW = "https://raw.githubusercontent.com/eggert/tz/main";
const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(here, "../server/engine/tz-country.ts");

const read = async (name) => {
  const dir = process.argv[2];
  if (dir) return fs.readFileSync(path.join(dir, name), "utf8");
  const response = await fetch(`${RAW}/${name}`);
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  return response.text();
};

const zoneTab = await read("zone.tab");
const backward = await read("backward");

// zone.tab: country, coordinates, zone name.
const base = new Map();
for (const line of zoneTab.split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [cc, , zone] = line.split("\t");
  if (/^[A-Z]{2}$/.test(cc) && zone) base.set(zone, cc);
}

// backward: "Link TARGET ALIAS [#= PREFERRED]".
const links = new Map();
for (const line of backward.split("\n")) {
  const match = line.match(/^Link\s+(\S+)\s+(\S+)(?:\s+#=\s*(\S+))?/);
  if (match) links.set(match[2], match[3] || match[1]);
}

// Names that carry no country (CET/EST/... now link to Brussels/Panama in tzdb).
const NON_GEO = /^(Etc\/.*|UTC|UCT|Universal|Zulu|GMT.*|Greenwich|Factory|CET|EET|MET|WET|EST|MST|HST|EST5EDT|CST6CDT|MST7MDT|PST8PDT)$/;
// Firefox resistFingerprinting, Tor Browser and Mullvad Browser all report
// Atlantic/Reykjavik; mapping it would inflate Iceland.
const SPOOFED = new Set(["Atlantic/Reykjavik"]);
// Links whose tzdb target lies in another country (they only share clocks).
const OVERRIDE = {
  "America/Coral_Harbour": "CA",
  "Antarctica/South_Pole": "AQ",
  "Atlantic/Jan_Mayen": "SJ",
  "Pacific/Johnston": "UM",
  "Pacific/Yap": "FM",
  "Africa/Timbuktu": "ML",
};

const map = new Map(base);
for (const [alias, target] of links) {
  if (map.has(alias) || NON_GEO.test(alias)) continue;
  if (OVERRIDE[alias]) {
    map.set(alias, OVERRIDE[alias]);
    continue;
  }
  let zone = target;
  for (let hops = 0; !base.has(zone) && links.has(zone) && hops < 5; hops += 1) zone = links.get(zone);
  if (base.has(zone)) map.set(alias, base.get(zone));
}
for (const zone of SPOOFED) map.delete(zone);

// Compact form, grouped by country: "CC:zone|zone;CC:zone".
const byCountry = new Map();
for (const [zone, cc] of map) byCountry.set(cc, [...(byCountry.get(cc) ?? []), zone]);
const compact = [...byCountry]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([cc, zones]) => `${cc}:${zones.sort().join("|")}`)
  .join(";");

const source = `/**
 * IANA time zone -> ISO 3166 country. GENERATED by
 * scripts/generate-tz-country.mjs from the IANA tz database (public domain);
 * do not edit by hand. ${map.size} zone names, ${byCountry.size} countries.
 * Non-geographic names (UTC, Etc/*, CET, EST, ...) and Atlantic/Reykjavik
 * (reported by anti-fingerprinting browsers) are deliberately absent.
 */
export const TZ_COUNTRY_DATA =
  ${JSON.stringify(compact)};
`;
fs.writeFileSync(outFile, source);
console.log(`wrote ${path.relative(process.cwd(), outFile)}: ${map.size} zones, ${byCountry.size} countries, ${Buffer.byteLength(source)} bytes`);
